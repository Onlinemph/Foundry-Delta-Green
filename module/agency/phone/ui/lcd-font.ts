export const GLYPH_W = 5
export const ADVANCE = 6
export const LINE_H = 10

/** Glyph rows as bit masks (bit 4 = leftmost). */
const GLYPHS = new Map<string, number[]>()
for (const [ch, rows] of Object.entries(RAW)) {
  GLYPHS.set(
    ch,
    rows.split('|').map(r => [...r].reduce((bits, c) => (bits << 1) | (c === '#' ? 1 : 0), 0))
  )
}

const QUOTES: Record<string, string> = { '‘': "'", '’': "'", '“': '"', '”': '"', '–': '-', '—': '-', ' ': ' ' }

/** Glyph rows for a character; unknown characters lose their accents, then fall back to '?'. */
export function glyph(ch: string): number[] {
  const direct = GLYPHS.get(ch) ?? GLYPHS.get(QUOTES[ch] ?? '')
  if (direct) return direct
  const plain = ch.normalize('NFD').replace(/[̀-ͯ]/g, '')
  return GLYPHS.get(plain) ?? GLYPHS.get('?')!
}

export function textWidth(text: string, scale = 1): number {
  return text.length ? (text.length * ADVANCE - 1) * scale : 0
}

/** Word-wrap to lines of at most `cols` characters; long words are broken. Keeps blank lines. */
export function wrapText(text: string, cols: number): string[] {
  const out: string[] = []
  for (const para of text.split('\n')) {
    let line = ''
    for (const word of para.split(' ')) {
      let w = word
      while (w.length > cols) {
        if (line) {
          out.push(line)
          line = ''
        }
        out.push(w.slice(0, cols))
        w = w.slice(cols)
      }
      if (!line) line = w
      else if (line.length + 1 + w.length <= cols) line += ' ' + w
      else {
        out.push(line)
        line = w
      }
    }
    out.push(line)
  }
  return out
}

/** Cut to `cols` with an ellipsis. */
export function clip(text: string, cols: number): string {
  return text.length > cols ? text.slice(0, Math.max(0, cols - 1)) + '…' : text
}
